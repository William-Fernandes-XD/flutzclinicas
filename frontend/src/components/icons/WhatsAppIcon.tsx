export function toWhatsAppUrl(raw: string): string {
  const digits = raw.replace(/\D/g, "");
  if (!digits) return "#";
  const withCountry = digits.startsWith("55") ? digits : `55${digits}`;
  return `https://wa.me/${withCountry}`;
}
