  empresa_id INT NOT NULL,
  codigo VARCHAR(80) NOT NULL,
  percentual_desconto DECIMAL(5,2) NOT NULL,
  data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  data_expiracao TIMESTAMP NOT NULL,
  status_id INT NOT NULL,
  usos_maximos INT NULL,
  usos_realizados INT NOT NULL DEFAULT 0,
  colaborador_criacao_id INT NULL,
  ultima_atualizacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_empresa_cupom_id PRIMARY KEY (empresa_cupom_id),
  CONSTRAINT uk_empresa_cupom_codigo UNIQUE (empresa_id, codigo),
  CONSTRAINT chk_empresa_cupom_percentual
    CHECK (percentual_desconto >= 0 AND percentual_desconto <= 100),
  CONSTRAINT chk_empresa_cupom_expiracao
    CHECK (data_expiracao > data_criacao),
  CONSTRAINT chk_empresa_cupom_usos_maximos
    CHECK (usos_maximos IS NULL OR usos_maximos >= 1),
  CONSTRAINT chk_empresa_cupom_usos_realizados
    CHECK (usos_realizados >= 0),
  CONSTRAINT fk_empresa_cupom_empresa
    FOREIGN KEY (empresa_id) REFERENCES empresa (empresa_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_empresa_cupom_status
    FOREIGN KEY (status_id) REFERENCES status (status_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_empresa_cupom_colaborador
    FOREIGN KEY (colaborador_criacao_id) REFERENCES colaborador (colaborador_id) ON DELETE SET NULL ON UPDATE CASCADE
