-- Slot ocupado também enquanto aguarda pagamento (profissional já atribuído).
CREATE OR REPLACE FUNCTION flutz.fn_agendamento_sem_conflito()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_ocupa boolean;
BEGIN
  SELECT s.codigo NOT IN ('CANCELADO', 'CANCELADO_CLIENTE', 'CANCELADO_CLINICA', 'RECUSADO', 'FALTOU', 'CONCLUIDO')
    INTO v_ocupa
  FROM flutz.agendamento_status s
  WHERE s.agendamento_status_id = NEW.agendamento_status_id;

  IF NOT COALESCE(v_ocupa, TRUE) THEN
    RETURN NEW;
  END IF;

  IF NEW.colaborador_id IS NOT NULL AND NEW.data_hora_fim IS NOT NULL THEN
    IF EXISTS (
      SELECT 1
      FROM flutz.agendamento a
      INNER JOIN flutz.agendamento_status s ON s.agendamento_status_id = a.agendamento_status_id
      WHERE a.colaborador_id = NEW.colaborador_id
        AND (TG_OP = 'INSERT' OR a.agendamento_id <> NEW.agendamento_id)
        AND s.codigo NOT IN ('CANCELADO', 'CANCELADO_CLIENTE', 'CANCELADO_CLINICA', 'RECUSADO', 'FALTOU', 'CONCLUIDO')
        AND a.data_hora_fim IS NOT NULL
        AND NEW.data_hora_inicio < a.data_hora_fim
        AND NEW.data_hora_fim > a.data_hora_inicio
    ) THEN
      RAISE EXCEPTION 'Colaborador ja possui agendamento neste horario.';
    END IF;
  END IF;

  IF NEW.colaborador_id IS NULL AND NEW.data_hora_fim IS NOT NULL THEN
    IF EXISTS (
      SELECT 1
      FROM flutz.agendamento a
      INNER JOIN flutz.agendamento_status s ON s.agendamento_status_id = a.agendamento_status_id
      WHERE a.empresa_id = NEW.empresa_id
        AND a.colaborador_id IS NULL
        AND (TG_OP = 'INSERT' OR a.agendamento_id <> NEW.agendamento_id)
        AND s.codigo IN ('CONFIRMADO', 'AGUARDANDO_CLIENTE', 'AGUARDANDO_PAGAMENTO')
        AND a.data_hora_fim IS NOT NULL
        AND NEW.data_hora_inicio < a.data_hora_fim
        AND NEW.data_hora_fim > a.data_hora_inicio
    ) THEN
      RAISE EXCEPTION 'Este horario ja esta confirmado na clinica.';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;
