function convertTypes(text) {
  return text
    .replace(/\bINT NOT NULL AUTO_INCREMENT\b/g, "INTEGER GENERATED BY DEFAULT AS IDENTITY")
    .replace(/\bTINYINT\(1\)/g, "BOOLEAN")
    .replace(/\bTINYINT\b/g, "SMALLINT")
    .replace(/\bDATETIME\b/g, "TIMESTAMP")
    .replace(/\bJSON\b/g, "JSONB")
    .replace(/\bBOOLEAN NOT NULL DEFAULT 0\b/g, "BOOLEAN NOT NULL DEFAULT FALSE")
    .replace(/\bBOOLEAN NOT NULL DEFAULT 1\b/g, "BOOLEAN NOT NULL DEFAULT TRUE")
    .replace(/ DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP/g, " DEFAULT CURRENT_TIMESTAMP")
    .replace(/\b(\w+)\s+IN\s+\(0,\s*1\)/g, "$1 IN (FALSE, TRUE)");
}

function extractColumnComments(block) {
  const comments = [];
  const re = /^\s+(\w+)\s+.+?\s+COMMENT\s+'((?:''|[^'])*)'/gm;
  let match;
  while ((match = re.exec(block))) {
    comments.push([match[1], match[2].replace(/''/g, "'")]);
  }
  return comments;
}

function stripInlineComments(block) {
  return block.replace(/\s+COMMENT\s+'((?:''|[^'])*)'/g, "");
}

function extractTableComment(block) {
  const match = block.match(/\)\s*ENGINE=InnoDB[\s\S]*COMMENT='((?:''|[^'])*)'/);
  return match ? match[1].replace(/''/g, "'") : null;
}

function extractIndexes(block) {
  const indexes = [];
  const re = /^\s+INDEX\s+(\w+)\s+\(([^)]+)\)\s*,?\s*$/gm;
  let match;
  while ((match = re.exec(block))) {
    indexes.push([match[1], match[2]]);
  }
  return indexes;
}

function removeStandaloneIndexes(block) {
  return block
    .replace(/,\n\s+INDEX\s+\w+\s+\([^)]+\)/g, "")
    .replace(/\n\s+INDEX\s+\w+\s+\([^)]+\)\s*,/g, "\n");
}

function convertCreateTable(block) {
  const nameMatch = block.match(/CREATE TABLE\s+(\w+)/);
  if (!nameMatch) return { sql: block, extras: [] };
  const name = nameMatch[1];
  const colComments = extractColumnComments(block);
  const tableComment = extractTableComment(block);
  const indexes = extractIndexes(block);

  let body = stripInlineComments(block);
  body = body.replace(/UNIQUE INDEX\s+(\w+)\s+\(([^)]+)\)/g, "CONSTRAINT $1 UNIQUE ($2)");
  body = body.replace(/PRIMARY KEY\s+\((\w+)\)/g, "CONSTRAINT pk_$1 PRIMARY KEY ($1)");
  body = removeStandaloneIndexes(body);
  body = body.replace(/\)\s*ENGINE=InnoDB[\s\S]*/g, ")");
  body = convertTypes(body);
  body = body.replace(`CREATE TABLE ${name}`, `CREATE TABLE flutz.${name}`);
  body = body.trim();
  if (!body.endsWith(";")) body += ";";

  const extras = [];
  for (const [idxName, cols] of indexes) {
    extras.push(`CREATE INDEX ${idxName} ON flutz.${name} (${cols});`);
  }
  if (/\bultima_atualizacao\b/.test(block)) {
    extras.push(
      `CREATE TRIGGER trg_${name}_ultima_atualizacao\nBEFORE UPDATE ON flutz.${name}\nFOR EACH ROW\nEXECUTE FUNCTION flutz.set_ultima_atualizacao();`,
    );
  }
  const esc = (s) => s.replace(/'/g, "''");
  if (tableComment) {
    extras.push(`COMMENT ON TABLE flutz.${name} IS\n  '${esc(tableComment)}';`);
  }
  for (const [col, comment] of colComments) {
    extras.push(`COMMENT ON COLUMN flutz.${name}.${col} IS\n  '${esc(comment)}';`);
  }
  return { sql: body, extras };
}

function convertAlterTable(block) {
  let body = convertTypes(block.replace(/`/g, ""));
  body = body.replace(/ALTER TABLE\s+(\w+)/, "ALTER TABLE flutz.$1");
  body = body.replace(/REFERENCES\s+(\w+)/g, "REFERENCES flutz.$1");
  return body.trim();
}

function extractSectionComments(text, from, to) {
  const slice = text.slice(from, to);
  return slice
    .split("\n")
    .filter(
      (ln) =>
        ln.startsWith("--") &&
        !/MySQL|InnoDB|utf8mb4|Workbench|Charset|Engine|DELIMITER/.test(ln),
    )
    .join("\n")
    .trim();
}

const raw = fs.readFileSync(src, "utf8").replace(/`/g, "");
const withoutTriggers = raw.replace(/DELIMITER \$\$[\s\S]*?DELIMITER ;/g, "\n");

const tableRe = /CREATE TABLE\s+\w+\s*\([\s\S]*?\)\s*ENGINE=InnoDB[\s\S]*?;/g;
const alterRe = /ALTER TABLE\s+\w+[\s\S]*?;/g;

const events = [];
for (const match of withoutTriggers.matchAll(tableRe)) {
  events.push({ type: "table", index: match.index, text: match[0] });
}
for (const match of withoutTriggers.matchAll(alterRe)) {
  events.push({ type: "alter", index: match.index, text: match[0] });
}
events.sort((a, b) => a.index - b.index);

const out = [HEADER];
let cursor = 0;
for (const event of events) {
  const comments = extractSectionComments(withoutTriggers, cursor, event.index);
  if (comments) out.push(comments, "");
  if (event.type === "table") {
    const { sql, extras } = convertCreateTable(event.text);
    out.push(sql);
    if (extras.length) out.push("", extras.join("\n\n"));
    out.push("");
  } else {
    out.push(convertAlterTable(event.text), "");
  }
  cursor = event.index + event.text.length;
}

out.push(RECUPERACAO_SENHA_SQL);
out.push(TRIGGER_SQL);

fs.mkdirSync(path.dirname(dst), { recursive: true });
fs.writeFileSync(dst, `${out.join("\n").trim()}\n`, "utf8");
console.log(`Wrote ${dst} (${events.filter((e) => e.type === "table").length} tables, ${events.filter((e) => e.type === "alter").length} alters)`);
