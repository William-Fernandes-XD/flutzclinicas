CREATE OR REPLACE FUNCTION flutz.fn_colaborador_horario_sem_sobrepor()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM flutz.colaborador_horario h
    WHERE h.colaborador_id = NEW.colaborador_id
      AND h.dia_semana = NEW.dia_semana
      AND (TG_OP = 'INSERT' OR h.colaborador_horario_id <> NEW.colaborador_horario_id)
      AND NEW.hora_inicio < h.hora_fim
      AND NEW.hora_fim > h.hora_inicio
  ) THEN
    RAISE EXCEPTION 'Colaborador ja possui faixa de horario sobreposta neste dia.';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_colaborador_horario_sem_sobrepor
BEFORE INSERT OR UPDATE ON flutz.colaborador_horario
FOR EACH ROW
EXECUTE FUNCTION flutz.fn_colaborador_horario_sem_sobrepor();

CREATE OR REPLACE FUNCTION flutz.fn_agendamento_sem_conflito()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.colaborador_id IS NOT NULL THEN
    IF EXISTS (
      SELECT 1
      FROM flutz.agendamento a
      INNER JOIN flutz.agendamento_status s
        ON s.agendamento_status_id = a.agendamento_status_id
      WHERE a.colaborador_id = NEW.colaborador_id
        AND (TG_OP = 'INSERT' OR a.agendamento_id <> NEW.agendamento_id)
        AND (s.codigo IS NULL OR s.codigo NOT IN ('CANCELADO', 'FALTOU'))
        AND NEW.data_hora_inicio < a.data_hora_fim
        AND NEW.data_hora_fim > a.data_hora_inicio
    ) THEN
      RAISE EXCEPTION 'Colaborador ja possui agendamento neste horario.';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_agendamento_sem_conflito
BEFORE INSERT OR UPDATE ON flutz.agendamento
FOR EACH ROW
EXECUTE FUNCTION flutz.fn_agendamento_sem_conflito();

CREATE OR REPLACE FUNCTION flutz.fn_fatura_token_limite()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_limite integer;
  v_usos integer;
BEGIN
  IF NEW.token_id IS NOT NULL THEN
    SELECT usos_maximos_por_empresa
      INTO v_limite
      FROM flutz.token
      WHERE token_id = NEW.token_id;

    IF v_limite IS NOT NULL THEN
      SELECT COUNT(*)
        INTO v_usos
        FROM flutz.fatura_assinatura
        WHERE empresa_id = NEW.empresa_id
          AND token_id = NEW.token_id
          AND status_fatura <> 'CANCELADA'
          AND (TG_OP = 'INSERT' OR fatura_assinatura_id <> NEW.fatura_assinatura_id);

      IF v_usos >= v_limite THEN
        RAISE EXCEPTION 'Token ja atingiu o limite de usos desta empresa.';
      END IF;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_fatura_token_limite
BEFORE INSERT OR UPDATE ON flutz.fatura_assinatura
FOR EACH ROW
EXECUTE FUNCTION flutz.fn_fatura_token_limite();

CREATE OR REPLACE FUNCTION flutz.fn_auditoria_acao_bloquear_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF OLD.anonimizado_em IS NOT NULL THEN
    RAISE EXCEPTION 'auditoria_acao ja anonimizada: UPDATE proibido.';
  END IF;
  IF NEW.anonimizado_em IS NULL
     OR NEW.auditoria_acao_id IS DISTINCT FROM OLD.auditoria_acao_id
     OR NEW.empresa_id IS DISTINCT FROM OLD.empresa_id
     OR NEW.ator_tipo IS DISTINCT FROM OLD.ator_tipo
     OR NEW.ator_id IS DISTINCT FROM OLD.ator_id
     OR NEW.pagina IS DISTINCT FROM OLD.pagina
     OR NEW.botao IS DISTINCT FROM OLD.botao
     OR NEW.data_acao IS DISTINCT FROM OLD.data_acao
     OR NEW.endereco_ip IS NOT NULL
     OR NEW.user_agent IS NOT NULL THEN
    RAISE EXCEPTION 'auditoria_acao: UPDATE so para anonimizar (limpar IP/UA e marcar anonimizado_em).';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_auditoria_acao_bloquear_update
BEFORE UPDATE ON flutz.auditoria_acao
FOR EACH ROW
EXECUTE FUNCTION flutz.fn_auditoria_acao_bloquear_update();

