CREATE SCHEMA IF NOT EXISTS flutz;
SET search_path TO flutz;

CREATE OR REPLACE FUNCTION flutz.set_ultima_atualizacao()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.ultima_atualizacao = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

