CREATE TABLE flutz.token (
  token_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  codigo_token VARCHAR(80) NOT NULL,
  percentual_desconto DECIMAL(5,2) NOT NULL,
  data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  data_expiracao TIMESTAMP NOT NULL,
  status_id INT NOT NULL,
  administrador_sistema_id INT NOT NULL,
  usos_maximos_por_empresa INT NULL,
  CONSTRAINT pk_token_id PRIMARY KEY (token_id),
  CONSTRAINT uk_token_codigo UNIQUE (codigo_token),



  CONSTRAINT chk_token_percentual
    CHECK (percentual_desconto >= 0 AND percentual_desconto <= 100),
  CONSTRAINT chk_token_expiracao
    CHECK (data_expiracao > data_criacao),
  CONSTRAINT chk_token_usos_maximos
    CHECK (usos_maximos_por_empresa IS NULL OR usos_maximos_por_empresa >= 1),
  CONSTRAINT fk_token_status
    FOREIGN KEY (status_id)
    REFERENCES status (status_id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
  CONSTRAINT fk_token_administrador_sistema
    FOREIGN KEY (administrador_sistema_id)
    REFERENCES administrador_sistema (administrador_sistema_id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE INDEX idx_token_status ON flutz.token (status_id);

CREATE INDEX idx_token_expiracao ON flutz.token (data_expiracao);

CREATE INDEX idx_token_administrador ON flutz.token (administrador_sistema_id);

